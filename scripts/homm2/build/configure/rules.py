#!/usr/bin/env python3
"""Every build.ninja rule declaration, in the stable emission order."""

from __future__ import annotations

PY = "python3"


def emit_rules(w) -> None:
    w.comment("generated by configure.py from config/units.toml - do not edit")
    w.variable("builddir", "build")
    # depfile/deps=gcc: cc_wrap writes $out.d (repo headers this obj includes) so ninja
    # recompiles on header edits — MSVC 4.2 has no /showIncludes, so cc_wrap scans them.
    w.rule("cl",
           command=f"{PY} -m homm2.build.cc_wrap --out $out --src $in -- $flags",
           depfile="$out.d", deps="gcc",
           description="cl $unit")
    # DATA/DATA_COMPGEN identities come from the source manifest; the
    # normalizer changes comparison-only symbol names, never linked objects.
    w.rule("canonicalize_data_symbols",
           command=(f"{PY} -m homm2.build.canonicalize_data_symbols "
                    "--input $in --output $out --sidecar $sidecar "
                    "--unit $unit --compgen-manifest "
                    "build/gen/compiler_generated_functions.csv "
                    "--data-manifest build/gen/delink_data_from_source.tsv "
                    "--data-base-root build/objdiff/base"),
           description="normalize-data $unit")
    w.rule("assert_weak_external_link_set",
           command=(f"{PY} -m homm2.build.canonicalize_data_symbols "
                    "--assert-weak-link-set $in --weak-stamp $out"),
           description="prove weak-external defaults")
    w.rule("canonicalize_relocs",
           command=(f"{PY} -m homm2.build.canonicalize_relocs "
                    "--unit $unit --base $base --target $in --output $out "
                    "--symbols build/gen/symbol_names.csv "
                    "--rel32-aliases config/reviewed_rel32_aliases.tsv"),
           description="normalize-relocs $unit")
    w.rule("implib_def",
           command=('wine "$$MSVC_DIR/bin/LIB.EXE" /NOLOGO /MACHINE:IX86 '
                    '/DEF:$in /OUT:$out'),
           description="lib $out")
    w.rule("implib_stub",
           command=(f"{PY} -m homm2.build.import_lib --exe $in "
                    "--dll $dll --out $out"),
           description="stub-implib $dll")
    w.rule("legacy_implib",
           command=(f"{PY} -m homm2.build.legacy_import_lib "
                    "--definition $in --out $out"),
           description="legacy-implib WING32.dll")
    w.rule("regular_implib",
           command=(f"{PY} -m homm2.build.regular_import_lib --exe $in "
                    "--dll $dll --out $out"),
           description="regular-implib $dll")
    w.rule("definition_implib",
           command=(f"{PY} -m homm2.build.regular_import_lib "
                    "--definition $in --dll $dll --out $out"),
           description="definition-implib $dll")
    w.rule("regular_vendor_implib",
           command=(f"{PY} -m homm2.build.regular_vendor_import_lib "
                    "--exe $in --dll $dll --definition $definition "
                    "--out $out $options"),
           description="regular-implib $dll")
    w.rule("definition_vendor_implib",
           command=(f"{PY} -m homm2.build.regular_vendor_import_lib "
                    "--definition-only --dll $dll --definition $in "
                    "--out $out $options"),
           description="definition-implib $dll")
    w.rule("patched_implib",
           command=(f"{PY} -m homm2.build.gen_vendor_imports "
                    "--definition $in --out $out --dll $dll "
                    "--symbol $symbol --lookup $lookup --hint $hint"),
           description="patched-implib $dll")
    w.rule("archive",
           command='wine "$$MSVC_DIR/bin/LIB.EXE" @$out.rsp',
           rspfile="$out.rsp",
           rspfile_content="/NOLOGO /MACHINE:IX86 /OUT:$out $in",
           description="archive $out")
    w.rule("extract_archive_member",
           command='llvm-ar p $in "$member" > $out',
           description="extract $member")
    w.rule("ml_omf",
           command=(f"{PY} -m homm2.build.ml_wrap "
                    "--src $in --out $out"),
           description="assemble-omf $in")
    w.rule("ml_coff",
           command=(f"{PY} -m homm2.build.ml_wrap "
                    "--coff --src $in --out $out"),
           description="assemble-coff $in")
    w.rule("link_exe",
           command=f"{PY} -m homm2.build.exact_link.plain --transform",
           description="plain retail-exact LINK.EXE HMM2PL.exe")
    w.rule("link_audit",
           command=(f"{PY} -m homm2.build.link_exe --audit-existing "
                    "--strict --out build/link/HMM2PL.exe"),
           description="link-audit HMM2PL.exe")
    w.rule("link_resources",
           command=(f"{PY} -m homm2.build.rc_res "
                    "--rc res/HMM2PL.rc --out build/link/HMM2PL.res "
                    "--verify-exe build/orig/HMM2PL.exe "
                    "--report build/link/HMM2PL.resources.json"),
           description="rc-res HMM2PL.res")
